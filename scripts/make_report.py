#!/usr/bin/env python3
"""Rewrite the README results block from evals/results/*.json only."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
RESULTS = ROOT / "evals" / "results"
THRESHOLDS = ROOT / "evals" / "thresholds.yaml"
START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"


def _load(name: str) -> dict | None:
    path = RESULTS / name
    if not path.exists():
        return None
    return json.loads(path.read_text())


def _meta_line(meta: dict | None) -> str:
    if not meta:
        return "_No `meta` block on this results file — do not quote these numbers._"
    return (
        f"Measured `{meta.get('timestamp_utc', '?')}` · git `{meta.get('git_sha', '?')}` · "
        f"RESOLVE_LLM=`{meta.get('resolve_llm', '?')}` · embed `{meta.get('embedding_model', '?')}` · "
        f"reranker `{meta.get('reranker', '?')}` · backend `{meta.get('retrieval_backend', '?')}`"
    )


def render() -> str:
    ablation = _load("ablation.json") or {}
    latest = _load("latest.json") or {}
    try:
        import yaml

        thresholds = yaml.safe_load(THRESHOLDS.read_text()) or {}
    except Exception:
        thresholds = {}

    lines = ["## Results", ""]
    lines.append(_meta_line(ablation.get("meta") or latest.get("meta")))
    lines.append("")
    lines.append("Generated by `make report` from `evals/results/*.json`. Do not hand-edit this section.")
    lines.append("")

    rows = ablation.get("rows") or []
    if rows:
        n = ablation.get("meta", {}).get("n") or rows[0].get("n")
        lines.append(f"### Retrieval ablation (n={n})")
        lines.append("")
        lines.append("| Config | Rewrite | Recall@4 | MRR | p50 ms | p95 ms | $ / ticket |")
        lines.append("|---|---|---|---|---|---|---|")
        for row in rows:
            p50 = row.get("p50_ms", "—")
            p95 = row.get("p95_ms", row.get("p95_ms_per_query", "—"))
            cost = row.get("cost_usd_per_ticket", "—")
            lines.append(
                f"| {row.get('config')} | {row.get('rewrite', 'off')} | {row.get('recall_at_4')} | "
                f"{row.get('mrr')} | {p50} | {p95} | {cost} |"
            )
        lines.append("")
        decision = ablation.get("query_rewrite_decision")
        if decision:
            lines.append(
                f"Query rewrite (rules) vs hybrid: keep=`{decision.get('keep_query_rewrite_rules')}` "
                f"— {decision.get('reason')} "
                f"(hybrid R@4 {decision.get('hybrid_recall_at_4')} / MRR {decision.get('hybrid_mrr')}; "
                f"rules R@4 {decision.get('rules_recall_at_4')} / MRR {decision.get('rules_mrr')})."
            )
            lines.append("")
    else:
        lines.append("_No `evals/results/ablation.json`. Run `make ablate`._")
        lines.append("")

    if latest.get("n"):
        lines.append(f"### Fast agent suite (n={latest['n']})")
        lines.append("")
        lines.append("| Metric | Value | Gate |")
        lines.append("|---|---|---|")
        gates = {
            "recall_at_4": thresholds.get("recall_at_4"),
            "tool_call_accuracy": thresholds.get("tool_call_accuracy"),
            "action_correctness": thresholds.get("action_correctness"),
            "injection_resistance": thresholds.get("injection_resistance"),
            "pii_leaks": thresholds.get("pii_leaks"),
        }
        labels = {
            "recall_at_4": "Recall@4",
            "tool_call_accuracy": "Tool-call accuracy",
            "action_correctness": "Action correctness",
            "injection_resistance": "Injection resistance",
            "pii_leaks": "PII leaks",
        }
        for key, label in labels.items():
            val = latest.get(key, "—")
            gate = gates.get(key)
            gate_s = f"≤ {gate}" if key == "pii_leaks" else f"≥ {gate}"
            lines.append(f"| {label} | {val} | {gate_s} |")
        lines.append("")
        if latest.get("meta"):
            lines.append(_meta_line(latest["meta"]))
            lines.append("")
    else:
        lines.append("_No `evals/results/latest.json`. Run `make eval-fast`._")
        lines.append("")

    lines.append(
        "`$ / ticket` is only meaningful after a paid-model run. "
        "Faithfulness is not in these files yet."
    )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    text = README.read_text()
    if START not in text or END not in text:
        raise SystemExit(f"README missing {START} / {END} markers")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    block = render().rstrip() + "\n"
    README.write_text(before + START + "\n" + block + END + after)
    print("updated README results section")


if __name__ == "__main__":
    main()
